'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('website/index.html','utf8');
assert.ok(html.includes("const WA_KEY='anichan:wa-handoff'"));
assert.ok(html.includes("sessionStorage.setItem(WA_KEY"));
assert.ok(html.includes("history.replaceState("),'Private URL fragment must be scrubbed');
assert.ok(html.includes("finishWaLogin()"));
assert.ok(html.includes("await send('/api/link/complete',{ticket})"),'Browser owns final account linking');
assert.ok(html.includes("current=data.account;await finishWaLogin()"),'Auto-link immediately after website login');
assert.ok(html.includes("await finishWaLogin();toast('Email verified successfully!')"),'Auto-link after email verification');
assert.ok(html.includes("grabWaTicket();try{const r=await api('/api/me')"),'Load ticket on first website visit');
assert.ok(!html.includes("send('/api/link/start'"),'Remove numeric linking code generation');
assert.ok(!html.includes('YOUR_8_DIGIT_CODE'),'No WhatsApp code instructions');
assert.ok(!html.includes('start-link'),'No chat-code button remains');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.ok(scripts.length);
const vm=require('node:vm');
for(const match of scripts)new vm.Script(match[1]);
console.log('PASS: all WhatsApp linking stays in browser, private fragment scrubbed, automatic signup/login/email continuation, no chat code UI');
